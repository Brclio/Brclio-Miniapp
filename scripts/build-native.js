#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'miniprogram/lib/duel.js');
function buildNative() {
  require('./prepare-duel-audio').prepareDuelAudio();
  require('./prepare-native-photos').prepareNativePhotos(false);
  const result = esbuild.buildSync({
    entryPoints: [path.join(root, 'minigame/lib/game-app.js')],
    bundle: true, write: false, format: 'cjs', platform: 'neutral', target: ['es2017'],
    legalComments: 'eof', banner: { js: '// Generated by scripts/build-native.js from the shared local game. Do not edit directly.' }
  });
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, result.outputFiles[0].contents);
  return result.outputFiles[0].text;
}
module.exports = { buildNative };
if (require.main === module) { buildNative(); console.log('Built the offline native reaction challenge: miniprogram/lib/duel.js'); }
