#!/usr/bin/env node
'use strict';
// Real FirstSight_Online photos, packaged offline in bounded native code packages.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const appRoot = path.join(root, 'miniprogram');
const dataRoot = path.join(appRoot, 'data');
const manifestFile = path.join(dataRoot, 'photo-assets.json');
const template = path.join(root, 'native/album');
const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
function imageSize(file) {
  const text = spawnSync('/usr/bin/sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' }).stdout;
  return { width: Number(text.match(/pixelWidth: (\d+)/)[1]), height: Number(text.match(/pixelHeight: (\d+)/)[1]) };
}
function convert(source, output, edge, quality) {
  const result = spawnSync('/usr/bin/sips', ['-Z', String(edge), '-s', 'format', 'jpeg', '-s', 'formatOptions', String(quality), source, '--out', output], { encoding: 'utf8' });
  if (result.status !== 0) throw new Error('Native photo conversion failed: ' + path.basename(source));
  return { bytes: fs.statSync(output).size, sha256: hash(output), ...imageSize(output) };
}
function writeData(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, '// Generated by scripts/prepare-native-photos.js.\nmodule.exports = ' + JSON.stringify(value) + ';\n');
}
function registerPhotoPackages(config, packages) {
  const others = (config.subPackages || []).filter(pack => !/^photo-\d+$/.test(pack.root) && pack.root !== 'photography');
  config.subPackages = packages.map(pack => ({ root: pack.root, pages: ['pages/album/index'] })).concat(others);
  config.preloadRule = Object.assign({}, config.preloadRule, {
    'pages/gallery/index': { network: 'all', packages: [packages[0].root] }
  });
  return config;
}
function prepareNativePhotos(refresh) {
  const source = JSON.parse(fs.readFileSync(path.join(root, 'web/projects/firstsight/original-data.json')));
  if (source.source.repository !== 'https://github.com/AndersonHJB/FirstSight_Online' || source.counts.collections !== 9 || source.counts.availablePhotoEntries !== 169) throw new Error('The corrected 169-photo source must be completely imported first.');
  fs.mkdirSync(dataRoot, { recursive: true });
  let manifest = fs.existsSync(manifestFile) ? JSON.parse(fs.readFileSync(manifestFile)) : null;
  if (refresh) {
    const cache = path.join(root, 'artifacts/native-photo-cache');
    fs.mkdirSync(cache, { recursive: true });
    const assets = source.assets.map(asset => {
      const input = path.join(root, 'web', asset.url.slice(1));
      const filename = path.basename(asset.url, path.extname(asset.url)) + '.jpg';
      const output = path.join(cache, filename);
      const details = convert(input, output, 1024, 35);
      return { sourceUrl: asset.url, sourceSha256: asset.sha256, sourceBlobSha: asset.sourceBlobSha, filename, ...details };
    });
    const bySource = new Map(assets.map(asset => [asset.sourceUrl, asset]));
    const packs = [];
    for (const collection of source.collections) {
      const collectionAssets = [...new Set(collection.photos.map(photo => photo.url))].map(url => bySource.get(url));
      let bytes = collectionAssets.reduce((n, asset) => n + asset.bytes, 0);
      // Keep one whole album in a package so the viewer never reads another
      // subpackage's assets. If necessary, reduce that album's display size.
      for (const quality of [28, 22]) {
        if (bytes <= 1700 * 1024) break;
        for (const asset of collectionAssets) Object.assign(asset, convert(path.join(root, 'web', asset.sourceUrl.slice(1)), path.join(cache, asset.filename), quality === 22 ? 896 : 1024, quality));
        bytes = collectionAssets.reduce((n, asset) => n + asset.bytes, 0);
      }
      if (bytes > 1700 * 1024) throw new Error('Album exceeds native package budget: ' + collection.id);
      let pack = packs.find(item => item.bytes + bytes <= 1700 * 1024);
      if (!pack) { pack = { root: 'photo-' + (packs.length + 1), ids: [], bytes: 0 }; packs.push(pack); }
      pack.ids.push(collection.id); pack.bytes += bytes;
      for (const asset of collectionAssets) {
        if (asset.pack && asset.pack !== pack.root) throw new Error('A source photo occurs across native packages');
        asset.pack = pack.root;
        asset.url = '/' + pack.root + '/assets/photos/' + asset.filename;
      }
    }
    const covers = source.collections.map(collection => {
      const output = path.join(cache, 'cover-' + collection.id + '.jpg');
      const details = convert(path.join(root, 'web', collection.cover.slice(1)), output, 640, 45);
      return { id: collection.id, sourceUrl: collection.cover, filename: collection.id + '.jpg', url: '/assets/photo-covers/' + collection.id + '.jpg', ...details };
    });
    // These roots contain only this generator's derivatives and data. Existing
    // album/page source templates live outside them and remain untouched.
    for (const entry of fs.readdirSync(appRoot, { withFileTypes: true })) {
      if (entry.isDirectory() && /^photo-\d+$/.test(entry.name)) fs.rmSync(path.join(appRoot, entry.name), { recursive: true });
    }
    for (const asset of assets) {
      const output = path.join(appRoot, asset.url.slice(1));
      fs.mkdirSync(path.dirname(output), { recursive: true });
      fs.copyFileSync(path.join(cache, asset.filename), output);
    }
    const coverRoot = path.join(appRoot, 'assets/photo-covers');
    fs.mkdirSync(coverRoot, { recursive: true });
    for (const cover of covers) fs.copyFileSync(path.join(cache, 'cover-' + cover.id + '.jpg'), path.join(appRoot, cover.url.slice(1)));
    fs.copyFileSync(path.join(appRoot, covers[0].url.slice(1)), path.join(appRoot, 'assets/firstsight-cover.jpg'));
    manifest = { format: 2, sourceRepository: source.source.repository, sourceCommit: source.source.commit, purpose: 'Offline JPEG display derivatives of upstream optimized WebP; original JPG files are not modified.', packages: packs, assets, covers };
    fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
  }
  if (!manifest || manifest.format !== 2 || manifest.sourceCommit !== source.source.commit || manifest.assets.length !== 169) throw new Error('Run npm run prepare:photos after a source update.');
  const bySource = new Map(manifest.assets.map(asset => [asset.sourceUrl, asset]));
  for (const asset of manifest.assets.concat(manifest.covers)) {
    const file = path.join(appRoot, asset.url.slice(1));
    if (!/^\/(?:photo-\d+\/assets\/photos|assets\/photo-covers)\/[a-z0-9-]+\.jpg$/.test(asset.url) || !fs.existsSync(file) || hash(file) !== asset.sha256) throw new Error('Native photo checksum mismatch: ' + asset.url);
  }
  for (const asset of source.assets) if (bySource.get(asset.url)?.sourceSha256 !== asset.sha256) throw new Error('Native photo source changed: ' + asset.url);
  const collections = source.collections.map(collection => {
    const pack = manifest.packages.find(item => item.ids.includes(collection.id));
    const cover = manifest.covers.find(item => item.id === collection.id);
    if (!pack || !cover) throw new Error('Album package missing');
    return { ...collection, cover: cover.url, nativePath: '/' + pack.root + '/pages/album/index?id=' + encodeURIComponent(collection.id), photos: collection.photos.map(photo => {
      const asset = bySource.get(photo.url);
      return { ...photo, url: asset.url, sourceSha256: asset.sourceSha256, sha256: asset.sha256, width: asset.width, height: asset.height, available: true, loadError: false };
    }) };
  });
  writeData(path.join(dataRoot, 'photos.js'), { collections });
  for (const pack of manifest.packages) {
    const packRoot = path.join(appRoot, pack.root);
    const packCollections = collections.filter(collection => pack.ids.includes(collection.id)).map(collection => ({ ...collection, cover: bySource.get(source.collections.find(item => item.id === collection.id).cover).url }));
    writeData(path.join(packRoot, 'data/photos.js'), { collections: packCollections });
    const page = path.join(packRoot, 'pages/album');
    fs.mkdirSync(page, { recursive: true });
    for (const ext of ['js', 'json', 'wxml', 'wxss']) fs.copyFileSync(path.join(template, 'index.' + ext), path.join(page, 'index.' + ext));
  }
  const configFile = path.join(appRoot, 'app.json');
  const config = JSON.parse(fs.readFileSync(configFile));
  config.pages = config.pages.filter(page => !page.startsWith('photography/') && page !== 'pages/album/index');
  if (!config.pages.includes('pages/gallery/index')) config.pages.splice(1, 0, 'pages/gallery/index');
  registerPhotoPackages(config, manifest.packages);
  fs.writeFileSync(configFile, JSON.stringify(config, null, 2) + '\n');
  return { count: manifest.assets.length, packages: manifest.packages.length, bytes: manifest.assets.reduce((n, asset) => n + asset.bytes, 0) };
}
module.exports = { prepareNativePhotos, registerPhotoPackages };
if (require.main === module) console.log(prepareNativePhotos(process.argv.includes('--refresh')));
