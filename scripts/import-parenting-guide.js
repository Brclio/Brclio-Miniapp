#!/usr/bin/env node
'use strict';

// Import only structured text from a user-supplied local course archive.
// Source files are data: no archive scripts, HTML, media, or remote URLs execute.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const REPO_ROOT = path.resolve(__dirname, '..');
const PACKAGE_TEXT_BUDGET = 1700 * 1024;
const OMITTED_TYPES = new Set(['audio', 'video', 'image']);
const BLOCK_TYPES = {
  paragraph: 'paragraph', header: 'heading', blockquote: 'quote',
  list: 'list', hr: 'divider', tip: 'paragraph',
  'label-group': 'heading', elite: 'quote', salutation: 'paragraph'
};

function normalizeText(value) {
  return String(value || '').replace(/\r\n?/g, '\n').replace(/\u00a0/g, ' ').trim();
}

// Apply the requested display names to imported copies only. This is a
// presentation edit, not a claim that the original course was authored by us.
function displayText(value) {
  return normalizeText(value)
    .replace(/Dr\s*[.．]?\s*魏\s*的?\s*家庭教育宝典/gi, '悦创育儿宝典')
    .replace(/Dr\s*[.．]?\s*魏/gi, '悦创')
    .replace(/魏坤琳/g, '悦创')
    .replace(/叨叨魏(?:老师)?|魏叨叨|魏老师|魏教授/g, '悦创')
    .replace('二是我的姓氏“魏”（拼音wei）在德文中读作why', '二是取了姓氏的谐音：以“魏”（拼音 wei）为例，在德文中读作 why')
    .replace(/章子怡/g, '林知夏');
}

function convertBlocks(blocks) {
  if (!Array.isArray(blocks)) throw new Error('Article blocks must be an array');
  return blocks.flatMap((block) => {
    if (OMITTED_TYPES.has(block.type)) return [];
    const type = BLOCK_TYPES[block.type];
    if (!type) throw new Error(`Unsupported source block type: ${block.type}`);
    // The archived personalized greeting is a template token, not reader text.
    let text = displayText(block.text);
    if (block.type === 'salutation') text = text.replace(/\$_IGET_USER_NAME_\$\s*[,，]?\s*/g, '');
    if (type === 'divider') return [{ type, text: '' }];
    if (!text) return [];
    return [{ type, text }];
  });
}

function readArchiveJson(sourceDir, relativePath) {
  const file = path.resolve(sourceDir, relativePath);
  if (!file.startsWith(sourceDir + path.sep)) throw new Error(`Invalid archive path: ${relativePath}`);
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

function buildGuide(sourceDirectory) {
  const sourceDir = path.resolve(sourceDirectory);
  const sourceCourse = readArchiveJson(sourceDir, 'course.json');
  const lessons = [...sourceCourse.lessons].sort((a, b) => a.order - b.order);
  if (lessons.length !== sourceCourse.expected_lesson_count) throw new Error('Course lesson count mismatch');
  if (new Set(lessons.map((lesson) => String(lesson.id))).size !== lessons.length) throw new Error('Duplicate article IDs');
  const COURSE = {
    title: '悦创育儿宝典',
    originalTitle: displayText(sourceCourse.title),
    author: '悦创',
    attributionLabel: '文字整理',
    source: '文字整理版',
    sourceUrl: sourceCourse.source_url,
    total: lessons.length
  };
  const SECTIONS = sourceCourse.sections.map((section) => ({
    id: String(section.id),
    title: displayText(section.title).replace(/[（(]\d+讲[）)]$/, ''),
    count: lessons.filter((lesson) => String(lesson.section_id) === String(section.id)).length,
    description: displayText(section.description).replace(/\\r\\n/g, '\n')
  }));
  const sectionsById = new Map(SECTIONS.map((section) => [section.id, section]));
  const firstPackageSections = new Set(SECTIONS.slice(0, 4).map((section) => section.id));
  const articles = lessons.map((lesson, index) => {
    const sectionId = String(lesson.section_id);
    const section = sectionsById.get(sectionId);
    if (!section) throw new Error(`Unknown section: ${sectionId}`);
    const blocks = convertBlocks(readArchiveJson(sourceDir, lesson.localized_blocks_path));
    if (!blocks.some((block) => block.text)) throw new Error(`Empty article: ${lesson.id}`);
    const wordCount = Array.from(blocks.map((block) => block.text).join('').replace(/\s/g, '')).length;
    return {
      id: String(lesson.id),
      title: displayText(lesson.title),
      sectionId,
      sectionTitle: section.title,
      summary: displayText(lesson.summary),
      order: index + 1,
      readingMinutes: Math.max(1, Math.ceil(wordCount / 500)),
      wordCount,
      sourceUrl: lesson.source_url,
      readerPath: firstPackageSections.has(sectionId) ? '/parenting/pages/article/index' : '/parenting-extra/pages/article/index',
      blocks
    };
  });
  const summary = (article) => article ? { id: article.id, title: article.title, readerPath: article.readerPath } : null;
  articles.forEach((article, index) => {
    article.previous = summary(articles[index - 1]);
    article.next = summary(articles[index + 1]);
  });
  const ARTICLES = articles.map(({ blocks, previous, next, ...meta }) => meta);
  return { COURSE, SECTIONS, ARTICLES, articles };
}

function serializeCatalog(guide) {
  return '// Generated by scripts/import-parenting-guide.js. Text metadata only.\n' +
    `module.exports = ${JSON.stringify({ COURSE: guide.COURSE, SECTIONS: guide.SECTIONS, ARTICLES: guide.ARTICLES }, null, 2)};\n`;
}

function serializeArticles(course, articles) {
  const byId = Object.fromEntries(articles.map((article) => [article.id, article]));
  return '// Generated by scripts/import-parenting-guide.js. Text only; no media or network access.\n' +
    `const COURSE = ${JSON.stringify(course)};\n` +
    `const ARTICLES = ${JSON.stringify(byId)};\n` +
    'function getArticle(id) { return Object.prototype.hasOwnProperty.call(ARTICLES, String(id)) ? ARTICLES[String(id)] : null; }\n' +
    'module.exports = { COURSE, getArticle };\n';
}

function importGuide(sourceDirectory, outputRoot = REPO_ROOT) {
  const guide = buildGuide(sourceDirectory);
  const files = {
    'miniprogram/parenting/data/catalog.js': serializeCatalog(guide),
    'miniprogram/parenting/data/guide.js': serializeArticles(guide.COURSE, guide.articles.filter((article) => article.readerPath.startsWith('/parenting/'))),
    'miniprogram/parenting-extra/data/guide.js': serializeArticles(guide.COURSE, guide.articles.filter((article) => article.readerPath.startsWith('/parenting-extra/')))
  };
  const packageBytes = {};
  for (const [file, content] of Object.entries(files)) {
    const packageName = file.split('/')[1];
    packageBytes[packageName] = (packageBytes[packageName] || 0) + Buffer.byteLength(content);
  }
  for (const [name, bytes] of Object.entries(packageBytes)) {
    if (bytes > PACKAGE_TEXT_BUDGET) throw new Error(`${name}: text data ${bytes} exceeds reserved data budget ${PACKAGE_TEXT_BUDGET}`);
  }
  for (const [file, content] of Object.entries(files)) {
    const destination = path.join(outputRoot, file);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, content);
  }
  return {
    articles: guide.ARTICLES.length,
    sections: guide.SECTIONS.length,
    packageBytes,
    textSha256: crypto.createHash('sha256').update(JSON.stringify(guide.articles.map(({ id, blocks }) => ({ id, blocks })))).digest('hex')
  };
}

if (require.main === module) {
  const sourceDirectory = process.argv[2];
  if (!sourceDirectory) {
    console.error('Usage: node scripts/import-parenting-guide.js /absolute/path/to/course-archive');
    process.exitCode = 1;
  } else {
    console.log(JSON.stringify(importGuide(sourceDirectory), null, 2));
  }
}

module.exports = { normalizeText, displayText, convertBlocks, buildGuide, importGuide, PACKAGE_TEXT_BUDGET };
